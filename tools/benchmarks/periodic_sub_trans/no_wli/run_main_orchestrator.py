from __future__ import annotations

from typing import Any, Callable, Mapping, MutableMapping


def run_main(
    *,
    state: MutableMapping[str, Any],
    main_fn: Callable[[], None],
    maybe_run_stage3_span_basin_k_sweep_fn: Callable[..., bool],
    bootstrap_main_run_fn: Callable[..., Mapping[str, Any]],
    execute_pipeline_from_startup_fn: Callable[..., None],
    direction_ltr: Any,
    direction_rtl: Any,
    require_assets_fn: Callable[..., Any],
    encode_long_plaintext_fn: Callable[..., Any],
    repo_root_fn: Callable[..., Any],
    make_flavor_run_dir_fn: Callable[..., Any],
    prepare_run_environment_fn: Callable[..., Any],
    load_proven_index_fn: Callable[..., Any],
    build_run_mode_info_fn: Callable[..., Any],
    oracle_mode_normalized_fn: Callable[..., str],
    apply_run_mode_fn: Callable[[], None],
    apply_kaeding_progress_settings_fn: Callable[[], None],
    apply_scoring_experiment_profile_fn: Callable[..., Any],
    build_run_config_fn: Callable[..., Any],
    build_no_wli_order_dispatch_payload_fn: Callable[..., Mapping[str, Any]],
    normalize_no_wli_order_fn: Callable[[str | None], str],
    persist_run_config_with_locks_fn: Callable[..., Any],
    resolve_repo_path_fn: Callable[..., Any],
    stage3_search_cfg_fn: Callable[..., Any],
    build_setup_logging_payload_fn: Callable[..., Any],
    emit_setup_logging_fn: Callable[..., Any],
    scorer_objective_summary_fn: Callable[..., str],
    weights_text_fn: Callable[..., str],
    scorer_cfg_for_output_fn: Callable[..., Any],
    scoring_meta_for_output_fn: Callable[..., Any],
    build_non_scoring_lock_payload_fn: Callable[..., Any],
    build_scoring_lock_payload_fn: Callable[..., Any],
    hash_payload_fn: Callable[..., str],
    write_json_fn: Callable[..., Any],
    git_short_fn: Callable[..., str],
    git_commit_fn: Callable[..., str],
    git_dirty_fn: Callable[..., bool],
    sha256_file_fn: Callable[..., str],
    to_repo_rel_path_fn: Callable[..., str],
    log_prefix: str,
) -> None:
    if maybe_run_stage3_span_basin_k_sweep_fn(
        state=state,
        canonical_run_mode_fn=state["_canonical_run_mode"],
        apply_profile_defaults_fn=state["_apply_profile_defaults"],
        main_fn=main_fn,
    ):
        return

    startup = bootstrap_main_run_fn(
        state=state,
        direction_ltr=direction_ltr,
        direction_rtl=direction_rtl,
        require_assets_fn=require_assets_fn,
        encode_long_plaintext_fn=encode_long_plaintext_fn,
        repo_root_fn=repo_root_fn,
        make_flavor_run_dir_fn=make_flavor_run_dir_fn,
        prepare_run_environment_fn=prepare_run_environment_fn,
        load_proven_index_fn=load_proven_index_fn,
        build_run_mode_info_fn=build_run_mode_info_fn,
        oracle_mode_normalized_fn=oracle_mode_normalized_fn,
        apply_run_mode_fn=apply_run_mode_fn,
        apply_kaeding_progress_settings_fn=apply_kaeding_progress_settings_fn,
        apply_scoring_experiment_profile_fn=apply_scoring_experiment_profile_fn,
        build_run_config_fn=build_run_config_fn,
        build_no_wli_order_dispatch_payload_fn=build_no_wli_order_dispatch_payload_fn,
        normalize_no_wli_order_fn=normalize_no_wli_order_fn,
        persist_run_config_with_locks_fn=persist_run_config_with_locks_fn,
        resolve_repo_path_fn=resolve_repo_path_fn,
        stage3_search_cfg_fn=stage3_search_cfg_fn,
        build_setup_logging_payload_fn=build_setup_logging_payload_fn,
        emit_setup_logging_fn=emit_setup_logging_fn,
        scorer_objective_summary_fn=scorer_objective_summary_fn,
        weights_text_fn=weights_text_fn,
        scorer_cfg_for_output_fn=scorer_cfg_for_output_fn,
        scoring_meta_for_output_fn=scoring_meta_for_output_fn,
        build_non_scoring_lock_payload_fn=build_non_scoring_lock_payload_fn,
        build_scoring_lock_payload_fn=build_scoring_lock_payload_fn,
        hash_payload_fn=hash_payload_fn,
        write_json_fn=write_json_fn,
        git_short_fn=git_short_fn,
        git_commit_fn=git_commit_fn,
        git_dirty_fn=git_dirty_fn,
        sha256_file_fn=sha256_file_fn,
        to_repo_rel_path_fn=to_repo_rel_path_fn,
        log_prefix=str(log_prefix),
    )

    execute_pipeline_from_startup_fn(
        state=state,
        startup=startup,
    )
